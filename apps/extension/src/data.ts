import {
  claudeReviewer,
  gptZeroDetector,
  pangramDetector,
  SEED_BRANDS,
  type AddressLabelList,
  type AiDetector,
  type AnalyzeContext,
  type DomainList,
  type PageReviewer,
} from "@satya/checks";

interface DomainListFile {
  source: string;
  kind: DomainList["kind"];
  domains: string[];
  allow?: string[];
}
interface NamedListFile {
  source: string;
  names: string[];
}
interface AddressListFile {
  source: string;
  labels: Record<string, string>;
}

async function loadJson<T>(path: string, fallback: T): Promise<T> {
  try {
    const res = await fetch(chrome.runtime.getURL(path));
    return res.ok ? ((await res.json()) as T) : fallback;
  } catch {
    return fallback;
  }
}

let cached: Promise<Omit<AnalyzeContext, "aiDetector">> | undefined;

/** Loads the public lists bundled with the extension (generated by scripts/import). */
export function loadContext(): Promise<Omit<AnalyzeContext, "aiDetector">> {
  cached ??= (async () => {
    const [domainLists, namedLists, addressLists] = await Promise.all([
      loadJson<DomainListFile[]>("data/domain-lists.json", []),
      loadJson<NamedListFile[]>("data/named-lists.json", []),
      loadJson<AddressListFile[]>("data/address-lists.json", []),
    ]);
    return {
      phishing: {
        brands: SEED_BRANDS,
        lists: domainLists.map((l) => ({
          source: l.source,
          kind: l.kind,
          domains: new Set(l.domains.map((d) => d.toLowerCase())),
          allow: l.allow ? new Set(l.allow.map((d) => d.toLowerCase())) : undefined,
        })),
      },
      namedLists,
      addressLists: addressLists.map(
        (l): AddressLabelList => ({
          source: l.source,
          labels: new Map(Object.entries(l.labels).map(([k, v]) => [k.toLowerCase(), v])),
        }),
      ),
    };
  })();
  return cached;
}

export type DetectorChoice = "none" | "pangram" | "gptzero";
export interface Settings {
  detector: DetectorChoice;
  apiKey: string;
  /** Anthropic API key for the AI page review. Empty = review off. */
  claudeKey: string;
}

export async function getSettings(): Promise<Settings> {
  const s = await chrome.storage.local.get(["detector", "apiKey", "claudeKey"]);
  return {
    detector: (s.detector as DetectorChoice) ?? "none",
    apiKey: (s.apiKey as string) ?? "",
    claudeKey: (s.claudeKey as string) ?? "",
  };
}

export async function saveSettings(s: Settings): Promise<void> {
  await chrome.storage.local.set(s);
}

export function detectorFor(s: Settings): AiDetector | undefined {
  if (!s.apiKey) return undefined;
  if (s.detector === "pangram") return pangramDetector(s.apiKey);
  if (s.detector === "gptzero") return gptZeroDetector(s.apiKey);
  return undefined;
}

export function reviewerFor(s: Settings): PageReviewer | undefined {
  return s.claudeKey ? claudeReviewer(s.claudeKey, { browser: true }) : undefined;
}
